import '../../data/models/enums.dart';
import 'diagram_model.dart';

class DiagramTemplate {
  const DiagramTemplate(this.id, this.name, this.description, this.build);
  final String id;
  final String name;
  final String description;
  final DiagramDocument Function() build;
}

DiagramShape _s(
  String id,
  DiagramShapeType type,
  double x,
  double y,
  String label, {
  double w = 150,
  double h = 80,
  String fill = '#F4E9D4',
  String stroke = '#8A6A31',
  DiagramMetadata metadata = const DiagramMetadata(),
}) => DiagramShape(
  id: id,
  type: type,
  x: x,
  y: y,
  width: w,
  height: h,
  label: label,
  style: DiagramStyle(fillColor: fill, strokeColor: stroke),
  metadata: metadata,
);

DiagramConnector _c(
  String id,
  String from,
  String to,
  String label, {
  DiagramAnchor fromAnchor = DiagramAnchor.right,
  DiagramAnchor toAnchor = DiagramAnchor.left,
  ConnectorKind kind = ConnectorKind.elbow,
}) => DiagramConnector(
  id: id,
  fromId: from,
  toId: to,
  label: label,
  fromAnchor: fromAnchor,
  toAnchor: toAnchor,
  kind: kind,
);

